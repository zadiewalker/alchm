// Crisis resource integration system
function generateCrisisResourceSystem() {
  return {
    // Location-aware resource delivery
    getLocalCrisisResources: function(userLocation) {
      const locationCode = userLocation?.country || 'US';
      const resources = this.crisis_resource_database[locationCode.toLowerCase()] || 
                       this.crisis_resource_database.united_states;
      
      return {
        immediate_emergency: "911", // Always show local emergency number
        primary_crisis_line: resources.national_resources?.[0] || {
          name: "988 Suicide & Crisis Lifeline", 
          phone: "988"
        },
        text_support: resources.national_resources?.find(r => r.text) || {
          name: "Crisis Text Line",
          text: "Text HOME to 741741"
        },
        youth_specific: resources.youth_specific_resources?.[0],
        local_directory: resources.local_directory || 
                        this.crisis_resource_database.international_resources.global_directory
      };
    },
    
    // Real-time resource verification
    verifyResourceAvailability: async function(resource) {
      try {
        // API call to verify resource is currently available
        const response = await fetch(`/api/verify-crisis-resource`, {
          method: 'POST',
          body: JSON.stringify({ resource }),
          headers: { 'Content-Type': 'application/json' }
        });
        
        return response.ok;
      } catch (error) {
        console.error('Resource verification failed:', error);
        return true; // Default to available for safety
      }
    },
    
    // Crisis intervention workflow
    handleCrisisDetection: function(crisisKeywords, userProfile) {
      const resources = this.getLocalCrisisResources(userProfile.location);
      const ageGroup = this.determineAgeGroup(userProfile.age);
      
      return {
        disclaimer: this.medical_disclaimers.crisis_intervention_disclaimer,
        immediate_resources: resources,
        age_appropriate_messaging: this.getAgeAppropriateMessages(ageGroup),
        parental_notification: ageGroup === 'minor' && userProfile.parent_contact,
        follow_up_resources: this.getFollowUpResources(userProfile)
      };
    }
  };
}

